#!/usr/bin/env python3
"""Inline sim.js into page.html, gzip it and write src/remote_page.h.

Run from arduino/joya-badge after editing remote/page.html or remote/sim.js:
    python3 remote/build_page.py
"""
import gzip
import pathlib

here = pathlib.Path(__file__).resolve().parent
page = (here / "page.html").read_text()
sim = (here / "sim.js").read_text()
tag = '<script src="sim.js"></script>'
assert tag in page, "page.html must load sim.js with the exact tag"
html = page.replace(tag, "<script>\n" + sim + "</script>")
gz = gzip.compress(html.encode(), 9, mtime=0)

rows = []
for i in range(0, len(gz), 16):
    rows.append("    " + ", ".join(f"0x{b:02x}" for b in gz[i : i + 16]) + ",")
out = (
    "// Generated by remote/build_page.py from remote/page.html + remote/sim.js.\n"
    "// Do not edit by hand.\n"
    "#ifndef JOYA_BADGE_REMOTE_PAGE_H\n#define JOYA_BADGE_REMOTE_PAGE_H\n\n"
    "#include <pgmspace.h>\n\n"
    f"// {len(html)} bytes of HTML, gzipped.\n"
    f"static const size_t kRemotePageGzLen = {len(gz)};\n"
    "static const uint8_t kRemotePageGz[] PROGMEM = {\n" + "\n".join(rows) + "\n};\n\n"
    "#endif  // JOYA_BADGE_REMOTE_PAGE_H\n"
)
(here.parent / "src" / "remote_page.h").write_text(out)
print(f"page {len(html)} bytes, gzipped {len(gz)} bytes -> src/remote_page.h")
